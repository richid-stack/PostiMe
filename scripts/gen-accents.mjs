// Generates theme/accents.css from src/theme/accents.json.
// Each accent gets: grain colours (a body, b shadow, c highlight), text colours for dark and light,
// and a 50..950 scale (as rgb triples) so Tailwind utilities like bg-accent-600/20 follow the chosen accent.
// Run: node scripts/gen-accents.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const accents = JSON.parse(readFileSync(new URL('../src/theme/accents.json', import.meta.url), 'utf8'));

const hexToRgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const rgbToHsl = ([r, g, b]) => {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
  if (max === min) return [0, 0, l * 100];
  const d = max - min, s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  const h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return [h * 60, s * 100, l * 100];
};
const hslToRgb = ([h, s, l]) => {
  h /= 360; s /= 100; l /= 100;
  const f = (n) => {
    const k = (n + h * 12) % 12, a = s * Math.min(l, 1 - l);
    return l - a * Math.max(-1, Math.min(k - 3, Math.min(9 - k, 1)));
  };
  return [f(0), f(8), f(4)].map((v) => Math.round(v * 255));
};
const triple = (rgb) => rgb.join(' ');

const scale = (hex) => {
  const [h, s, l] = rgbToHsl(hexToRgb(hex));
  const l500 = Math.min(l + 8, 58), l400 = Math.max(60, l500 + 6);
  const steps = {
    50: [96, 0.55], 100: [91, 0.65], 200: [82, 0.75], 300: [72, 0.85], 400: [l400, 0.92], 500: [l500, 1],
    600: [l, 1], 700: [Math.max(l - 8, 10), 0.97], 800: [Math.max(l - 15, 8), 0.9], 900: [Math.max(l - 22, 6), 0.8], 950: [Math.max(l - 30, 4), 0.7],
  };
  const out = {};
  for (const [k, [lightness, sat]] of Object.entries(steps)) out[k] = hslToRgb([h, Math.min(s * sat, 100), lightness]);
  out[600] = hexToRgb(hex);
  return out;
};
const lighten = (hex, by) => { const [h, s, l] = rgbToHsl(hexToRgb(hex)); return hslToRgb([h, s, Math.min(l + by, 95)]); };
const toHex = (rgb) => '#' + rgb.map((v) => v.toString(16).padStart(2, '0')).join('');

const block = (sel, a) => {
  const sc = scale(a.a);
  const lines = [
    `  --ac-a: ${a.a};`,
    `  --ac-b: ${a.b};`,
    `  --ac-c: ${a.c};`,
    `  --ac-strong: ${toHex(lighten(a.a, 6))};`,
    `  --ac-text-d: ${a.textDark};`,
    `  --ac-text-l: ${a.textLight};`,
    `  --ac-rgb: ${triple(hexToRgb(a.a))};`,
    ...Object.entries(sc).map(([k, v]) => `  --ac-${k}: ${triple(v)};`),
  ];
  return `${sel} {\n${lines.join('\n')}\n}\n`;
};

let css = `/* GENERATED by scripts/gen-accents.mjs from src/theme/accents.json. Do not edit by hand. */\n`;
css += block(':root', accents[0]);
for (const a of accents.slice(1)) css += '\n' + block(`:root[data-accent="${a.id}"]`, a);
writeFileSync(new URL('../theme/accents.css', import.meta.url), css);
console.log(`wrote theme/accents.css (${accents.length} accents)`);
